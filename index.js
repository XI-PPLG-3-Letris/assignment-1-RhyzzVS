let tambah = (a, b) => {
    return a + b
}
let kurang = (a, b) => {
    return a - b
}
let kali = (a, b) => {
    return a * b
}
let bagi = (a, b) => {
    return a / b
}
let pangkat = (a, b) => {
    return a ** b
}
let modulus = (a, b) => {
    return a % b
}

console.log(tambah(5, 5))
console.log(kurang(25, 5))
console.log(kali(5, 15))
console.log(bagi(5, 10))
console.log(pangkat(9, 5))
console.log(modulus(5,2))